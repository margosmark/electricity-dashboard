/**
 * Direct tests for the commodity split (t_cb0cf70f — Defect C).
 *
 * `commodity.ts`'s header has always said "covered by commodity.test.ts" —
 * until this card that file did not exist, so `splitFeed`,
 * `commodityPresence` and `primaryCommodity` were only exercised
 * INDIRECTLY, through single-commodity fixtures in commodityProbe.test.ts.
 * No test anywhere pinned the mixed-document shapes, which is how a
 * bills-only half could be dropped by a commit gate while every suite
 * stayed green.
 *
 * FIXTURE POLICY: SYNTHETIC only (tests/fixtures/ — see README there).
 * The mixed fixture is the bills-only-half shape the security gate's F2
 * probe uploaded: electric INTERVAL rows + gas BILLING PERIODS and ZERO
 * gas interval rows (generated by scripts/generate-mixed-fixture.mjs).
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

import {
  parseGreenButtonFeed,
  type DataPoint,
  type UsageSummary,
} from '@/lib/energy';
import { enrichGasSummaries, isGasFeed } from '@/lib/gasBillUi';
import type { GasPoint } from '@/lib/storage';
import {
  commodityPresence,
  extractElectricPoints,
  extractGasPoints,
  primaryCommodity,
  splitFeed,
  splitSummaries,
  type FeedSplit,
} from '@/lib/commodity';

const read = (name: string): string =>
  readFileSync(join(__dirname, '../../tests/fixtures', name), 'utf8');

/** Parse a fixture the way both entry paths do: enrich gas, then split. */
function splitFixture(name: string): FeedSplit {
  const feed = parseGreenButtonFeed(read(name));
  const summaries = isGasFeed(feed.summaries) ? enrichGasSummaries(feed) : feed.summaries;
  return splitFeed({ groups: feed.groups, summaries });
}

/** Synthetic half-shapes that no committed fixture carries on its own. */
const point = (t: number): DataPoint => ({ timestamp: t, usage_kwh: 1 });
const gasPoint = (t: number): GasPoint => ({ timestamp: t, duration_s: 3600, volume_m3: 1 });
/**
 * A minimal but REAL `UsageSummary`: `isGasSummary` reads `volume.uom` and
 * `items[].note`, so a bare `{}` would throw rather than classify. Electric
 * = no volume; gas = uom 42 (the marker `isGasSummary` trusts).
 */
const summary = (gas: boolean): UsageSummary => ({
  source: 'UsageSummary',
  start: 1_700_000_000,
  duration: 2_592_000,
  startDate: '2023-11-14',
  endDate: '2023-12-14',
  days: 30,
  billLastPeriod: null,
  billToDate: null,
  costAdditionalLastPeriod: null,
  currency: 124,
  consumption: null,
  volume: gas ? { scaled: 1, value: 1, powerOfTenMultiplier: 0, uom: 42 } : null,
  items: [],
});
const splitOf = (over: Partial<FeedSplit>): FeedSplit => ({
  electric: [],
  gas: [],
  electricSummaries: [],
  gasSummaries: [],
  ...over,
});

/* ==========================================================================
 * splitFeed — one document → two disjoint buckets
 * ========================================================================== */

describe('splitFeed', () => {
  it('electric fixture: intervals in, no gas bucket created', () => {
    const feed = parseGreenButtonFeed(read('synthetic.xml'));
    const split = splitFeed({ groups: feed.groups, summaries: feed.summaries });
    expect(split.electric.length).toBeGreaterThan(0);
    expect(split.gas).toEqual([]);
    expect(split.gasSummaries).toEqual([]);
  });

  it('gas fixture: periods in, no electric bucket created', () => {
    const split = splitFixture('enbridge-gas-synthetic.xml');
    expect(split.gasSummaries.length).toBeGreaterThan(0);
    expect(split.electric).toEqual([]);
    expect(split.electricSummaries).toEqual([]);
    // The Enbridge extract carries volume intervals too (5 rows).
    expect(split.gas.length).toBe(5);
  });

  it('MIXED fixture: electric intervals + gas periods, NO gas intervals', () => {
    // The bills-only-half shape: exactly what the F2 gate probe uploaded.
    const split = splitFixture('mixed-commodity-synthetic.xml');
    expect(split.electric.length).toBe(68); // the whole electric feed
    expect(split.gasSummaries.length).toBe(10); // every Enbridge period
    expect(split.gas).toEqual([]); // ← the half a points-gate would drop
    expect(split.electricSummaries).toEqual([]); // synthetic.xml has no bills
  });

  it('classifies periods by isGasSummary, not by a volume field', () => {
    // The electric fixture's summaries carry `volume` too — only uom/Enbridge
    // markers mean gas (documented rule in commodity.ts).
    const feed = parseGreenButtonFeed(read('usage-summary-synthetic.xml'));
    const { electric, gas } = splitSummaries(feed.summaries);
    expect(feed.summaries.length).toBeGreaterThan(0);
    expect(electric.length).toBe(feed.summaries.length);
    expect(gas).toEqual([]);
  });

  it('extract helpers never cross types', () => {
    const mixed = splitFixture('mixed-commodity-synthetic.xml');
    expect(mixed.electric.every((p) => typeof p.usage_kwh === 'number')).toBe(true);
    expect(mixed.gas.every((p) => typeof p.volume_m3 === 'number')).toBe(true);
    // extract* are the same functions splitFeed composes — direct pins.
    const feed = parseGreenButtonFeed(read('mixed-commodity-synthetic.xml'));
    expect(extractElectricPoints(feed.groups).length).toBe(mixed.electric.length);
    expect(extractGasPoints(feed.groups)).toEqual(mixed.gas);
  });
});

/* ==========================================================================
 * commodityPresence — points OR periods, never "rows only"
 * ========================================================================== */

describe('commodityPresence', () => {
  it('both halves via INTERVALS', () => {
    expect(commodityPresence(splitOf({ electric: [point(1)], gas: [gasPoint(1)] }))).toEqual({
      electricity: true,
      gas: true,
      none: false,
    });
  });

  it('both halves when gas is PERIODS-ONLY (the F2 shape)', () => {
    // This is the regression pin: gas has no interval rows, only billing
    // periods — presence must still say gas, or a routing gate drops it.
    const presence = commodityPresence(
      splitOf({ electric: [point(1)], gasSummaries: [summary(true)] }),
    );
    expect(presence.gas).toBe(true);
    expect(presence.electricity).toBe(true);
    expect(presence.none).toBe(false);
  });

  it('electricity is PERIODS-ONLY when the doc has gas intervals', () => {
    const presence = commodityPresence(
      splitOf({ gas: [gasPoint(1)], electricSummaries: [summary(false)] }),
    );
    expect(presence.electricity).toBe(true);
    expect(presence.gas).toBe(true);
  });

  it('single-commodity shapes', () => {
    expect(commodityPresence(splitOf({ electric: [point(1)] }))).toEqual({
      electricity: true,
      gas: false,
      none: false,
    });
    expect(commodityPresence(splitOf({ gasSummaries: [summary(true)] }))).toEqual({
      electricity: false,
      gas: true,
      none: false,
    });
  });

  it('empty split → none (the honest refusal)', () => {
    expect(commodityPresence(splitOf({}))).toEqual({
      electricity: false,
      gas: false,
      none: true,
    });
  });

  it('matches splitFeed on the mixed fixture', () => {
    const presence = commodityPresence(splitFixture('mixed-commodity-synthetic.xml'));
    expect(presence).toEqual({ electricity: true, gas: true, none: false });
  });
});

/* ==========================================================================
 * primaryCommodity — which section an upload opens on
 * ========================================================================== */

describe('primaryCommodity', () => {
  it('null when the document carries nothing', () => {
    expect(primaryCommodity(splitOf({}))).toBeNull();
  });

  it('the only commodity present wins', () => {
    expect(primaryCommodity(splitOf({ electric: [point(1)] }))).toBe('electricity');
    expect(primaryCommodity(splitOf({ gas: [gasPoint(1)] }))).toBe('gas');
    // Bills-only: a periods-only half is still a half — it routes.
    expect(primaryCommodity(splitOf({ electricSummaries: [summary(false)] }))).toBe(
      'electricity',
    );
    expect(primaryCommodity(splitOf({ gasSummaries: [summary(true)] }))).toBe('gas');
  });

  it('mixed with ENBRIDGE periods leads gas (the documented tie-break)', () => {
    // `isGasFeed(gasSummaries)` decides before any counting: a mixed feed
    // whose gas half is Enbridge-shaped opens on gas.
    const mixed = splitFixture('mixed-commodity-synthetic.xml');
    expect(isGasFeed(mixed.gasSummaries)).toBe(true);
    expect(primaryCommodity(mixed)).toBe('gas');
  });

  it('mixed without gas-feed markers: more gas intervals wins the tie', () => {
    // No gas PERIODS at all → `isGasFeed([])` is false, so the count
    // tie-break decides: whichever commodity has more intervals leads.
    const tie = splitOf({
      electric: [point(1)],
      gas: [gasPoint(1), gasPoint(2)],
    });
    expect(isGasFeed(tie.gasSummaries)).toBe(false);
    expect(primaryCommodity(tie)).toBe('gas');
    const electricLed = splitOf({
      electric: [point(1), point(2), point(3)],
      gas: [gasPoint(1)],
    });
    expect(primaryCommodity(electricLed)).toBe('electricity');
  });

  it('every presence shape routes somewhere (never null when data exists)', () => {
    const shapes: FeedSplit[] = [
      splitOf({ electric: [point(1)] }),
      splitOf({ gas: [gasPoint(1)] }),
      splitOf({ electric: [point(1)], gasSummaries: [summary(true)] }),
      splitOf({ gas: [gasPoint(1)], electricSummaries: [summary(false)] }),
      splitOf({ electricSummaries: [summary(false)], gasSummaries: [summary(true)] }),
      splitFixture('mixed-commodity-synthetic.xml'),
    ];
    for (const s of shapes) {
      expect(primaryCommodity(s), JSON.stringify(s)).not.toBeNull();
    }
  });
});
