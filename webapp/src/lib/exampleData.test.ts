const TZ = 'America/Toronto';
const partFmt = new Intl.DateTimeFormat('en-CA', {
  timeZone: TZ,
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
  hour: '2-digit',
  hour12: false,
  weekday: 'short',
});

function local(utcSec: number) {
  const out: Record<string, string> = {};
  for (const p of partFmt.formatToParts(new Date(utcSec * 1000))) {
    if (p.type !== 'literal') out[p.type] = p.value;
  }
  const dow = { Sun: 0, Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5, Sat: 6 }[out.weekday] as number;
  return {
    year: +out.year,
    month: +out.month,
    day: +out.day,
    hour: out.hour === '24' ? 0 : +out.hour,
    dow,
    key: `${out.year}-${out.month}-${out.day}`,
  };
}

const xml = fs.readFileSync(SAMPLE, 'utf8');
const groups = parseGreenButtonUsagePoints(xml);
const rows = combineUsagePointGroups(groups);
// Intl formatting is expensive; resolve Toronto local time ONCE per reading.
const locs = rows.map((r) => local(r.timestamp));

describe('example fixture — provenance and identity', () => {
  it('says plainly that it is example data and not real usage', () => {
    expect(xml).toContain('EXAMPLE DATA - NOT REAL USAGE');
    expect(xml).toContain('Synthetic demo data');
    expect(EXAMPLE_DATA_LABEL).toMatch(/example data/i);
  });

  it('carries no account, address, email or name that could be a real meter', () => {
    expect(xml).not.toContain('@');
    expect(xml).not.toMatch(/account\s*(number|no|#)/i);
    expect(xml).not.toMatch(/\b[A-Z]\d[A-Z] \d[A-Z]\d\b/); // Ontario postal code
    // Names/meter ids: the only identifiers are the generator + timestamp tags.
    expect(xml).not.toMatch(/<mrid>|<name>|<Email>/);
  });

  it('is regenerated by a committed, deterministic script', () => {
    expect(xml).toContain('generate-example-fixture.mjs');
    expect(xml).toContain('Regenerate:');
  });
});

describe('example fixture — parser path', () => {
  it('parses as a single-meter feed with a full year plus a deterministic early October window', () => {
    expect(groups).toHaveLength(1);
    expect(rows).toHaveLength(8904);
    // Sorted, finite, non-zero, sane per-hour magnitude for a house.
    for (let i = 0; i < rows.length; i++) {
      expect(Number.isFinite(rows[i].usage_kwh)).toBe(true);
      expect(rows[i].usage_kwh).toBeGreaterThan(0);
      expect(rows[i].usage_kwh).toBeLessThan(20);
      if (i > 0) expect(rows[i].timestamp).toBeGreaterThan(rows[i - 1].timestamp);
    }
  });

  it('is strictly hourly — DST shows as a missing/duplicated LOCAL hour, not a gap', () => {
    // Every UTC step is exactly one hour.
    for (let i = 1; i < rows.length; i++) {
      expect(rows[i].timestamp - rows[i - 1].timestamp).toBe(3600);
    }
    // Spring forward (2026-03-08): 23 readings, no 02:00 local.
    const spring = rows.filter((r) => local(r.timestamp).key === '2026-03-08');
    expect(spring).toHaveLength(23);
    expect(spring.some((r) => local(r.timestamp).hour === 2)).toBe(false);
    // Fall back (2025-11-02): 25 readings, 01:00 local appears twice.
    const fall = rows.filter((r) => local(r.timestamp).key === '2025-11-02');
    expect(fall).toHaveLength(25);
    expect(fall.filter((r) => local(r.timestamp).hour === 1)).toHaveLength(2);
  });

  it('covers Oct 1 2025 through Oct 6 2026 local time', () => {
    const first = local(rows[0].timestamp);
    const last = local(rows[rows.length - 1].timestamp);
    expect([first.year, first.month, first.day]).toEqual([2025, 10, 1]);
    expect([last.year, last.month, last.day]).toEqual([2026, 10, 6]);
    expect(first.hour).toBe(0);
    expect(last.hour).toBe(23);
  });
});

describe('example fixture — the patterns the button promises', () => {
  const byHour = (pred: (l: ReturnType<typeof local>) => boolean) =>
    rows.filter((_, i) => pred(locs[i]));

  it('has a real EV overnight block: Sun–Thu 00:00–03:59 is ~3.3 kW, Fri–Sat is not', () => {
    const evHours = byHour((l) => l.hour < 4 && l.dow >= 0 && l.dow <= 4);
    const idleHours = byHour((l) => l.hour < 4 && l.dow >= 5);
    const mean = (rs: typeof rows) => rs.reduce((s, r) => s + r.usage_kwh, 0) / rs.length;

    // 5 nights/wk × 4 h × 52 wks ≈ 1 040 eligible hours in a year.
    expect(evHours.length).toBeGreaterThan(900);
    // Mean over EVERY eligible hour, including the ~25% that do not charge.
    expect(mean(evHours)).toBeGreaterThan(2.5);
    // At least 70% of eligible nights actually charge (3+ hours ≥ 3 kWh).
    const nights = new Map<string, { dow: number; kwh: number[] }>();
    for (let i = 0; i < rows.length; i++) {
      const l = locs[i];
      if (l.hour >= 4) continue;
      const entry = nights.get(l.key) ?? { dow: l.dow, kwh: [] };
      entry.kwh.push(rows[i].usage_kwh);
      nights.set(l.key, entry);
    }
    const eligible = [...nights.values()].filter((n) => n.dow <= 4); // Sun–Thu
    const charging = eligible.filter(
      (n) => n.kwh.filter((v) => v >= 3).length >= 3,
    ).length;
    expect(charging / eligible.length).toBeGreaterThan(0.7);

    expect(idleHours.length).toBeGreaterThan(400); // 2 days × 4 h × 52 wks
    expect(mean(idleHours)).toBeLessThan(1.0);
  });

  it('has weekday laundry/dishwasher hits that land in TOU On-Peak hours', () => {
    // Summer On-Peak is 11:00–17:00: washer 12:00 + dryer 13:00 both land here.
    const summerNoon = byHour(
      (l) => l.dow >= 1 && l.dow <= 5 && l.hour === 12 && l.month >= 5 && l.month <= 10,
    );
    expect(summerNoon.length).toBeGreaterThan(100); // ~26 weeks × 5 weekdays
    expect(summerNoon.filter((r) => r.usage_kwh >= 1.5).length).toBeGreaterThan(40);

    // The dryer runs at 13:00 — deep inside the summer 11:00-17:00 On-Peak
    // window, and the clearest on-peak hit in the whole fixture.
    const summerDryer = byHour(
      (l) => l.dow >= 1 && l.dow <= 5 && l.hour === 13 && l.month >= 5 && l.month <= 10,
    );
    expect(summerDryer.length).toBeGreaterThan(100);
    expect(summerDryer.filter((r) => r.usage_kwh >= 2).length).toBeGreaterThan(45);

    // Winter On-Peak is 17:00–19:00: the evening dryer/dishwasher lands here.
    const winterEvening = byHour(
      (l) => l.dow >= 1 && l.dow <= 5 && l.hour === 18 && (l.month <= 4 || l.month >= 11),
    );
    expect(winterEvening.filter((r) => r.usage_kwh >= 2.5).length).toBeGreaterThan(50);
  });

  it('varies by season — no flat line pretending to be a year', () => {
    const monthly = new Map<string, number>();
    for (let i = 0; i < rows.length; i++) {
      const l = locs[i];
      const key = `${l.year}-${String(l.month).padStart(2, '0')}`;
      monthly.set(key, (monthly.get(key) ?? 0) + rows[i].usage_kwh);
    }
    // The final six October days deliberately exist only to exercise the
    // early-month projection; they are not a comparable monthly total.
    monthly.delete('2026-10');
    expect(monthly.size).toBe(12);
    const totals = [...monthly.values()];
    const mean = totals.reduce((s, v) => s + v, 0) / totals.length;
    const min = Math.min(...totals);
    const max = Math.max(...totals);
    // Every month within a plausible household band, and a real swing
    // between the heating/cooling seasons and the shoulder months.
    expect(min).toBeGreaterThan(500);
    expect(max).toBeLessThan(1600);
    expect((max - min) / mean).toBeGreaterThan(0.15);
  });

  it('totals to a believable household: ~32 kWh/day incl. the EV', () => {
    const total = rows.reduce((s, r) => s + r.usage_kwh, 0);
    const perDay = total / (rows.length / 24);
    expect(perDay).toBeGreaterThan(25);
    expect(perDay).toBeLessThan(40);
  });
});

describe('example fixture — what the app does with it', () => {
  const processed = processRawData(rows, RATES);

  it('prices all three plans and finds anomalies (July heat wave, holidays)', () => {
    expect(processed).toHaveLength(8904);
    expect(processed.every((d) => d.costTOU >= 0 && d.costULO >= 0)).toBe(true);
    const anomalies = detectAnomalies(processed, processed);
    expect(anomalies.length).toBeGreaterThanOrEqual(1);
  });

  it('opens a source-backed provisional bill at the deterministic early-month cutoff', () => {
    const projection = projectMonthBill(processed, 'TOU', new Date(2026, 9, 6));
    expect(projection.ready).toBe(true);
    expect(projection.monthLabel).toBe('October 2026');
    expect(projection.monthDaysCovered).toBe(6);
  });

  it('produces recurring On-Peak blocks — the Shift Optimizer has a story to tell', () => {
    const analysis = analyzeTouShifts(processed, 'TOU', RATES[2]);
    expect(analysis.emptyReason).toBeNull();
    expect(analysis.blocks.length).toBeGreaterThan(0);
    // At least one block is the weekday-noon laundry in its On-Peak tier.
    expect(analysis.blocks.some((b) => b.tier === 'on-peak')).toBe(true);
    expect(analysis.totalMonthlySavings).toBeGreaterThan(0);
  });
});

describe('loadExampleReadings — the fetch path the button uses', () => {
  it('returns the parsed readings from the bundled URL', async () => {
    const fetcher = (async () => ({
      ok: true,
      text: async () => xml,
    })) as unknown as typeof fetch;

    const result = await loadExampleReadings(fetcher);
    expect(result.ok).toBe(true);
    if (result.ok) {
      expect(result.readings).toHaveLength(8904);
      expect(EXAMPLE_DATA_URL).toBe('/samples/example-usage.xml');
    }
  });

  it('never throws at the caller — a failed fetch is an explanation', async () => {
    const fetcher = (async () => {
      throw new Error('offline');
    }) as unknown as typeof fetch;

    const result = await loadExampleReadings(fetcher);
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.detail).toMatch(/example data/i);
      expect(result.detail).toMatch(/upload/i);
    }
  });

  it('reports a document that parsed to nothing instead of loading an empty chart', async () => {
    const fetcher = (async () => ({
      ok: true,
      text: async () => '<?xml version="1.0"?><feed></feed>',
    })) as unknown as typeof fetch;

    const result = await loadExampleReadings(fetcher);
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.detail).toMatch(/no readings/i);
  });
});
