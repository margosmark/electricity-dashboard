/**
 * Wave H item 1 — the sample-data fixture, tested on the parser path FIRST.
 *
 * The fixture is `public/samples/example-usage.xml`, served to anyone who
 * clicks "Try with example data". Before any UI exists, this file pins what
 * that document actually is: a synthetic one-year Green Button feed with the
 * shapes the button promises (EV overnight block, on-peak appliance hits,
 * seasonal swing) — and nothing that could be a real account.
 *
 * Regenerate with `node scripts/generate-example-fixture.mjs`; the file is
 * seed-deterministic, so these assertions are stable forever.
 */

