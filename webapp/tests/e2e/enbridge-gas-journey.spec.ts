import { test, expect, type Page } from '@playwright/test';
import path from 'node:path';

/**
 * Enbridge Gas (commodity 7) — the FULL import journey in a real browser
 * (t_b0ecf9f4), extending the `journey.spec.ts` full-journey pattern.
 *
 * The flow a gas customer actually walks: land on an empty profile → upload
 * the Extract through the same file input a real download takes → 10 monthly
 * bill periods render with the file's own dollars and m³ → the money table
 * carries the feed's two figures and their difference → the language switch
 * shows the gas copy in French → a reload brings the dataset back from
 * localStorage → and the two honesty rules hold at the DOM level (no kWh unit
 * on a gas surface; a period with no IntervalBlock says so instead of 0).
 *
 * FIXTURE POLICY: SYNTHETIC only — `tests/fixtures/enbridge-gas-synthetic.xml`
 * (generated by `scripts/generate-enbridge-gas-fixture.mjs`). The owner's real
 * EGD export carries his name, home address, account number, meter serial and
 * agreement id and must never enter this repo, a fixture, or a PR. The
 * synthetic file reproduces the real tag/string patterns (10 UsageSummary
 * periods, 5 IntervalBlocks, the money/volume/rate vocabulary) — same
 * convention as `utilitySamples.test.ts` / `usageSummary.test.ts`.
 *
 * Standing rules: manual file upload only, no utility-portal automation, no
 * credentials, no email to any utility/vendor about Green Button.
 */

const FIXTURE = path.resolve(__dirname, '../../tests/fixtures/enbridge-gas-synthetic.xml');

/** The file's 10 billing periods, oldest first, with the Amount Due it states. */
const PERIOD_STARTS = [
  '2025-12-25',
  '2026-01-27',
  '2026-02-26',
  '2026-03-26',
  '2026-04-28',
  '2026-05-27',
  '2026-06-24',
  '2026-07-27',
  '2026-08-27',
  '2026-09-25',
] as const;

const AMOUNT_DUE = [175.76, 153.06, 117.35, 84.75, 65.45, 132.06, 85.37, 119.04, 93.33, 72.47];
const TOTAL_GAS_CHARGES = [161.89, 153.06, 117.35, 84.75, 65.45, 132.06, 80.07, 119.04, 93.33, 66.29];

/** Current − previous meter read, per period (m³, as the bill states them). */
const METER_READ_DELTAS = [427, 386, 268, 176, 112, 347, 161, 295, 206, 112];

/** IntervalBlock coverage: 4 monthly blocks + one 1-day stub, 5 periods none. */
const INTERVAL_STATES = [
  'present',
  'present',
  'present',
  'present',
  'stub',
  'absent',
  'absent',
  'absent',
  'absent',
  'absent',
] as const;

/** Amount Due − Total Gas Charges: unexplained in the feed, in exactly 3 of 10. */
const DELTAS = [13.87, 0, 0, 0, 0, 0, 5.3, 0, 0, 6.18];

/** $1,098.64 = Σ Amount Due over the 10 periods (the app never sums it). */
const AMOUNT_DUE_SUM = 1098.64;

const money = (n: number) => `$${n.toFixed(2)}`;

/** Land on a fresh profile and push the fixture through the real upload input. */
async function landAndImport(page: Page): Promise<void> {
  const resp = await page.goto('/');
  expect(resp?.status()).toBe(200);
  // Fresh profile: nothing stored yet — the empty state is the starting point.
  expect(await page.evaluate(() => localStorage.getItem('energy_data_v2'))).toBeNull();
  expect(await page.evaluate(() => localStorage.getItem('usage_summaries'))).toBeNull();
  await expect(page.getByText('Drop XML Here')).toBeVisible({ timeout: 30_000 });

  await page.locator('input[aria-label="Upload Green Button XML"]').setInputFiles(FIXTURE);
  await expect(page.getByText('Drop XML Here')).toBeHidden({ timeout: 60_000 });
}

/** Open a toolbar tab by its locale-independent testid. */
async function openTab(page: Page, tab: 'tab-plans' | 'tab-money' | 'tab-analytics'): Promise<void> {
  await page.getByTestId(tab).click();
  await expect(page.getByTestId(tab)).toHaveAttribute('aria-selected', 'true');
}

const periods = (page: Page) => page.locator('[data-testid="gas-period"]');

test.describe('Enbridge gas import journey', () => {
  test('empty state → synthetic Enbridge usage file → 10 bill periods with feed-exact values', async ({
    page,
  }) => {
    test.setTimeout(120_000);
    expect(FIXTURE.endsWith('enbridge-gas-synthetic.xml')).toBe(true);

    await landAndImport(page);

    await openTab(page, 'tab-plans');
    await expect(periods(page)).toHaveCount(10, { timeout: 30_000 });

    // Every period, in feed order, with the Amount Due the file states.
    const starts = await periods(page).evaluateAll((els) =>
      els.map((el) => el.getAttribute('data-period-start')),
    );
    expect(starts).toEqual([...PERIOD_STARTS]);

    const shownAmounts = await page.getByTestId('gas-amount-due').allTextContents();
    expect(shownAmounts.map((t) => t.trim())).toEqual(AMOUNT_DUE.map(money));

    // First period: the header's billed volume and the meter reads behind it.
    const first = periods(page).first();
    await expect(first).toContainText(money(AMOUNT_DUE[0]));
    await expect(first.getByTestId('gas-header-volume')).toContainText('429.0 m³ billed');
    await expect(first.getByTestId('gas-volume-billed')).toHaveAttribute('data-m3', '429.0');
    await expect(first.getByTestId('gas-volume-reads')).toContainText(
      `difference between reads: ${METER_READ_DELTAS[0]} m³`,
    );
    // Granularity is stated, not implied: monthly, not hourly.
    await expect(first).toContainText('monthly billing periods');

    // The dataset really landed in localStorage (what a reload will read back)
    // — under the GAS key space the commodity split (t_8a9038d6, AC1) moved it
    // to: a gas import writes only `gas_usage_summaries` / `energy_gas_v2` and
    // never addresses the electric keys. So on this fresh profile BOTH electric
    // keys are ABSENT (null) — deliberately `null`, not `[]` / `{"points":[]}`:
    // an electric key holding an empty payload would mean this gas import
    // wrote it. (Measured at c30cf46: the only keys present are
    // `energy_gas_v2`, `gas_usage_summaries`, `oeo_commodity`.)
    const stored = await page.evaluate(() =>
      JSON.parse(localStorage.getItem('gas_usage_summaries') || '[]'),
    );
    expect(stored).toHaveLength(10);
    expect(await page.evaluate(() => localStorage.getItem('usage_summaries'))).toBeNull();
    expect(await page.evaluate(() => localStorage.getItem('energy_data_v2'))).toBeNull();
  });

  test('money tab: the ten on-screen Amount Due figures sum to $1,098.64', async ({ page }) => {
    test.setTimeout(120_000);
    await landAndImport(page);
    await openTab(page, 'tab-money');

    const table = page.getByTestId('gas-money-table');
    await expect(table).toBeVisible();
    const rows = table.locator('[data-testid="gas-money-row"]');
    await expect(rows).toHaveCount(10);

    // Read the figures the SCREEN shows; the app deliberately never adds them
    // up (its own caption says so), so the total is this test's arithmetic.
    await expect(page.getByTestId('gas-money-not-summed')).toContainText(
      'this app does not add these lines up to a total',
    );

    const cells = await rows.evaluateAll((trs) =>
      trs.map((tr) => Array.from(tr.querySelectorAll('td')).map((td) => (td.textContent || '').trim())),
    );
    const amountsDue = cells.map((c) => Number(c[2].replace(/[^0-9.]/g, '')));
    expect(amountsDue).toEqual(AMOUNT_DUE);
    const totals = cells.map((c) => Number(c[1].replace(/[^0-9.]/g, '')));
    expect(totals).toEqual(TOTAL_GAS_CHARGES);

    const summed = Math.round(amountsDue.reduce((a, b) => a + b, 0) * 100) / 100;
    expect(summed, `Σ Amount Due from the rendered table = ${summed}`).toBe(AMOUNT_DUE_SUM);

    // The 3 periods where Amount Due ≠ Total Gas Charges stay labelled
    // unexplained-in-feed; the other 7 are quiet.
    const reconciliation = await rows.evaluateAll((trs) =>
      trs.map((tr) => ({
        delta: tr.getAttribute('data-delta'),
        state: tr.getAttribute('data-reconciliation'),
      })),
    );
    expect(reconciliation.map((r) => Number(r.delta))).toEqual(DELTAS);
    expect(reconciliation.filter((r) => r.state === 'unexplained-in-feed')).toHaveLength(3);
    expect(reconciliation.filter((r) => r.state === 'equal')).toHaveLength(7);
  });

  test('language switch renders the gas copy in French', async ({ page }) => {
    test.setTimeout(120_000);
    await landAndImport(page);
    await openTab(page, 'tab-plans');

    const toggle = page.getByTestId('locale-toggle');
    await expect(toggle).toHaveAttribute('data-locale', 'en');
    await toggle.click();
    await expect(toggle).toHaveAttribute('data-locale', 'fr');

    // Plans: the gas badge and the interval sentences, translated.
    const first = periods(page).first();
    await expect(first.getByTestId('gas-badge')).toHaveText('Gaz naturel');
    await expect(first.getByTestId('gas-interval-state')).toContainText("Relevé d'intervalle");
    await expect(periods(page).nth(5).getByTestId('gas-interval-state')).toContainText(
      "Aucune donnée d'intervalle dans le fichier",
    );
    // Money: the caption and the first row compose in fr-CA (comma decimal,
    // currency after the figure) instead of inheriting "$175.76".
    await openTab(page, 'tab-money');
    await expect(page.getByTestId('gas-money-not-summed')).toContainText(
      'Listées telles que rapportées',
    );
    const firstRow = page.getByTestId('gas-money-row').first();
    await expect(firstRow).toContainText('25 déc. 2025');
    // fr-CA money composes "175,76 $" (comma decimal, NBSP before the
    // symbol) — assert the digits, not the separator Playwright would have
    // to normalise away.
    await expect(firstRow).toContainText('175,76');
    await expect(firstRow).toContainText('13,87');
  });

  test('reload: the gas dataset comes back from localStorage', async ({ page }) => {
    test.setTimeout(120_000);
    await landAndImport(page);
    await openTab(page, 'tab-plans');
    await expect(periods(page)).toHaveCount(10);

    await page.reload();
    // R1 (4c6eec3): restored summary-only storage (gas_usage_summaries=10 —
    // the split moved the R1 data to the gas key) is DATA, not an empty
    // profile — the first-run upload modal must NOT re-open over it. The
    // empty-storage half of that contract is asserted in landAndImport above
    // (modal visible on a genuinely fresh profile) and in Dashboard.test.tsx's
    // summary-only reload suite.
    await expect(page.getByText('Drop XML Here')).toBeHidden({ timeout: 10_000 });
    await expect(page.getByRole('dialog')).toHaveCount(0);

    await openTab(page, 'tab-plans');
    await expect(periods(page)).toHaveCount(10, { timeout: 30_000 });
    await expect(page.getByTestId('gas-amount-due').first()).toHaveText(money(AMOUNT_DUE[0]));
    await expect(periods(page).first().getByTestId('gas-volume-reads')).toContainText(
      `difference between reads: ${METER_READ_DELTAS[0]} m³`,
    );

    await openTab(page, 'tab-money');
    await expect(page.getByTestId('gas-money-row')).toHaveCount(10);
    // Post-reload the GAS key space carries the dataset back; the electric
    // keys are still untouched by a gas import (absent here, as before the
    // reload) — see the split-key comment in the first test.
    const stored = await page.evaluate(() =>
      JSON.parse(localStorage.getItem('gas_usage_summaries') || '[]'),
    );
    expect(stored).toHaveLength(10);
    expect(await page.evaluate(() => localStorage.getItem('usage_summaries'))).toBeNull();
    expect(await page.evaluate(() => localStorage.getItem('energy_data_v2'))).toBeNull();
    // Still no modal after the full post-reload walk — guards against a
    // late-appearing dialog over restored data (a modal that opened mid-test
    // would already have blocked the tab clicks above).
    await expect(page.getByRole('dialog')).toHaveCount(0);
  });

  test('honesty at the DOM level: no kWh unit on a gas surface, absence labelled not zero', async ({
    page,
  }) => {
    test.setTimeout(120_000);
    await landAndImport(page);

    // Walk every tab that renders gas data. Two disclaimers are ALLOWED to
    // name kWh, because they say the opposite of showing a unit: the import
    // notice ("…none of it was priced or added to the kWh totals") and the
    // analytics skip card ("kWh charts are electricity views and are not
    // shown here"). Everywhere else — any gas figure, any panel — the token
    // must be absent, and no kWh VALUE may render anywhere on the profile.
    const DISCLOSURES = ['series-notes-notice', 'gas-analytics-skip'];

    await openTab(page, 'tab-plans');
    await expect(page.getByTestId('series-notes-notice')).toBeVisible();

    let disclosureTokens = 0;
    for (const tab of ['tab-plans', 'tab-money', 'tab-analytics'] as const) {
      await openTab(page, tab);

      // (a) The surfaces that render gas FIGURES never say kWh at all.
      for (const sel of [
        '[data-testid="gas-period"]',
        '[data-testid="gas-money-section"]',
        '[data-testid="actual-bill"]',
        '[data-testid="tab-panel-plans"]',
        '[data-testid="tab-panel-money"]',
      ]) {
        const hits = await page.locator(sel).evaluateAll((els) =>
          els.map((el) => ((el.textContent || '').match(/kWh/gi) || []).length),
        );
        expect(
          hits.reduce((a, b) => a + b, 0),
          `${sel} on ${tab} must not show a kWh unit`,
        ).toBe(0);
      }

      // (b) No kWh VALUE anywhere: a number with a kWh unit, or ¢/kWh.
      const figures = await page.evaluate(
        () => document.body.innerText.match(/(?:\d[\d,.]*\s*kWh|¢\/kWh)/gi) || [],
      );
      expect(figures, `${tab}: a kWh figure must never render on a gas profile`).toEqual([]);

      // (c) Every remaining kWh token lives inside one of the two disclosures.
      const outside = await page.evaluate((allowed: string[]) => {
        const hits: string[] = [];
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let n: Node | null;
        while ((n = walker.nextNode())) {
          const text = n.textContent || '';
          if (!/kWh/i.test(text)) continue;
          let permitted = false;
          for (let e: Element | null = n.parentElement; e; e = e.parentElement) {
            const id = e.getAttribute('data-testid');
            if (id && allowed.includes(id)) {
              permitted = true;
              break;
            }
          }
          if (!permitted) hits.push(text.trim().slice(0, 100));
        }
        return hits;
      }, DISCLOSURES);
      expect(outside, `${tab}: kWh text outside a disclosure`).toEqual([]);

      disclosureTokens = Math.max(
        disclosureTokens,
        await page.evaluate(
          (id) =>
            ((document.querySelector(`[data-testid="${id}"]`)?.textContent || '').match(/kWh/gi) ||
              []).length,
          'series-notes-notice',
        ),
      );
    }
    // The volume-row disclosure really is rendering (the ban above is not
    // passing vacuously on a page that never mentions kWh).
    expect(disclosureTokens, 'the import-honesty notice must explain the volume rows').toBeGreaterThan(0);

    // Absence is a sentence, never a zero: 5 periods have no IntervalBlock.
    await openTab(page, 'tab-plans');
    const states = await page.getByTestId('gas-interval-state').evaluateAll((els) =>
      els.map((el) => el.getAttribute('data-state')),
    );
    expect(states).toEqual([...INTERVAL_STATES]);

    const absent = page.locator('[data-testid="gas-interval-state"][data-state="absent"]');
    await expect(absent).toHaveCount(5);
    for (let i = 0; i < 5; i++) {
      const box = absent.nth(i);
      await expect(box).toContainText('No interval data in the feed for this period');
      await expect(box).toContainText('This is not zero usage');
      expect(await box.textContent()).not.toMatch(/0\s*m³/);
    }
    // The one 1-day block says what it is rather than passing as a month.
    await expect(page.locator('[data-testid="gas-interval-state"][data-state="stub"]')).toContainText(
      'not a monthly reading',
    );
  });
});
