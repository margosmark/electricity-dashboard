import { test, expect, type Page } from '@playwright/test';
import path from 'node:path';

/**
 * The 23-series volume wall (t_1d93a874) — the shipped-acceptance miss.
 *
 * Mark's export rendered 23 "loaded as volume" sentences that differed only in
 * their `{label}` (`upId · meterId · unit`), so grouping by the RENDERED
 * sentence (t_8a9038d6) yielded 23 groups of 1 and the wall survived the fix.
 * This spec pushes the committed synthetic reproduction of that shape through
 * the real upload input and asserts what a reader must see: ONE line that
 * states the count in words, its ×23 badge, and a disclosure that still lists
 * all 23 notes verbatim.
 *
 * FIXTURE POLICY: SYNTHETIC only — `tests/fixtures/volume-series-wall-fixture.xml`
 * (generated by `scripts/generate-volume-series-wall-fixture.mjs`). Every id
 * in it is invented; no utility export and no personal data is involved.
 *
 * Run: `SMOKE_BASE_URL=<origin> PW_CHROMIUM_PATH=/usr/bin/chromium npx playwright test tests/e2e/volume-notes-wall.spec.ts`
 */

const FIXTURE = path.resolve(__dirname, '../../tests/fixtures/volume-series-wall-fixture.xml');

/** Fresh profile, then the fixture through the same input a real download takes. */
async function importWall(page: Page): Promise<void> {
  const resp = await page.goto('/');
  expect(resp?.status()).toBe(200);
  expect(await page.evaluate(() => localStorage.getItem('energy_data_v2'))).toBeNull();
  expect(await page.evaluate(() => localStorage.getItem('energy_gas_v2'))).toBeNull();
  await expect(page.getByText('Drop XML Here')).toBeVisible({ timeout: 30_000 });

  await page.locator('input[aria-label="Upload Green Button XML"]').setInputFiles(FIXTURE);
  await expect(page.getByText('Drop XML Here')).toBeHidden({ timeout: 60_000 });
}

test('a 23-series volume wall renders ONE line, with every note behind the disclosure', async ({
  page,
}) => {
  await importWall(page);

  const notice = page.getByTestId('series-notes-notice');
  await expect(notice).toBeVisible({ timeout: 30_000 });

  // ONE line — the wall is gone — and it says the count in words.
  const lines = page.getByTestId('series-note-detail');
  await expect(lines).toHaveCount(1);
  await expect(lines.first()).toContainText('23 series were loaded as volume');
  await expect(lines.first()).toContainText('4 reading(s)');
  await expect(page.getByTestId('series-note-count')).toHaveText('×23');

  // Nothing is concealed: the disclosure still carries every note, in feed
  // order, each with its own label.
  const disclosure = page.getByTestId('series-notes-details');
  await expect(disclosure).toBeVisible();
  await disclosure.locator('summary').click();
  await expect(page.getByTestId('series-note-raw')).toHaveCount(23);
  await expect(page.getByTestId('series-note-raw').first()).toContainText('READ0001');
  await expect(page.getByTestId('series-note-raw').last()).toContainText('READ0023');

  // A single-UsagePoint file never renders the picker, so the notice is the
  // only surface these sentences can reach the reader on.
  await expect(page.getByTestId('usage-point-picker')).toHaveCount(0);
});
